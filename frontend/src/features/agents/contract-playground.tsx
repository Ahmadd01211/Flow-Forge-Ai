"use client";
import { useState } from "react";
import Link from "next/link";
import {
  ArrowLeft,
  Check,
  CircleAlert,
  FlaskConical,
  LoaderCircle,
  ShieldCheck,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge, ErrorNotice, PageHeader } from "@/components/shared/ui";
import { api } from "@/lib/api/client";
import type { AgentVersion, ExampleResult } from "@/lib/api/types";

export function ContractPlayground({
  version,
  canEdit = true,
}: {
  version: AgentVersion;
  canEdit?: boolean;
}) {
  const [input, setInput] = useState(
      '{\n  "ticket": "My order arrived damaged."\n}',
    ),
    [output, setOutput] = useState('{\n  "priority": "urgent"\n}'),
    [includeOutput, setIncludeOutput] = useState(true),
    [result, setResult] = useState<ExampleResult | null>(null),
    [error, setError] = useState(""),
    [busy, setBusy] = useState(false);
  async function validate() {
    setBusy(true);
    setError("");
    setResult(null);
    try {
      const body = {
        input: JSON.parse(input),
        ...(includeOutput ? { output: JSON.parse(output) } : {}),
      };
      setResult(
        await api<ExampleResult>(
          `/workspaces/${version.workspace_id}/agents/${version.agent_id}/versions/${version.id}/validate-example`,
          { method: "POST", body: JSON.stringify(body) },
        ),
      );
    } catch (e) {
      setError(
        e instanceof SyntaxError
          ? "Example inputs and outputs must contain valid JSON."
          : e instanceof Error
            ? e.message
            : "Contract validation failed.",
      );
    } finally {
      setBusy(false);
    }
  }
  return (
    <>
      <Link
        className="text-link playground-back"
        href={`/w/${version.workspace_id}/agents/${version.agent_id}?tab=versions`}
      >
        <ArrowLeft size={14} />
        Back to agent history
      </Link>
      <PageHeader
        eyebrow="CHECK THE CONTRACT BEFORE THE CALL"
        title="Contract playground"
        description={`Validate example data against ${version.name} · snapshot v${version.number}.`}
        action={
          <Badge tone="purple">
            <FlaskConical size={12} />
            No model call
          </Badge>
        }
      />
      <div className="contract-scope">
        <ShieldCheck size={20} />
        <div>
          <strong>Schema validation only</strong>
          <p>
            Examples below are manually supplied, not generated by an agent.
            Validation checks data shape, never instruction quality or model
            behavior. Inputs and outputs are not stored.
          </p>
        </div>
      </div>
      {error && <ErrorNotice message={error} />}
      <div className="contract-layout">
        <section className="panel contract-inputs">
          <div className="panel-header">
            <h2>Example data</h2>
            <Badge>Snapshot v{version.number}</Badge>
          </div>
          <div className="contract-editors">
            <label>
              Example input JSON
              <textarea
                className="json-editor"
                spellCheck={false}
                rows={10}
                value={input}
                onChange={(e) => {
                  setInput(e.target.value);
                  setResult(null);
                }}
              />
            </label>
            <label className="contract-output-toggle">
              <input
                type="checkbox"
                checked={includeOutput}
                onChange={(e) => {
                  setIncludeOutput(e.target.checked);
                  setResult(null);
                }}
              />
              Validate a manually supplied example output
            </label>
            {includeOutput && (
              <label>
                Example output JSON
                <textarea
                  className="json-editor"
                  spellCheck={false}
                  rows={8}
                  value={output}
                  onChange={(e) => {
                    setOutput(e.target.value);
                    setResult(null);
                  }}
                />
              </label>
            )}
            <Button onClick={validate} disabled={busy || !canEdit}>
              {busy ? (
                <LoaderCircle size={16} className="spin" />
              ) : (
                <FlaskConical size={16} />
              )}
              Validate contract
            </Button>
            {!canEdit && (
              <p className="muted">
                An editor role is required to validate example data.
              </p>
            )}
          </div>
        </section>
        <aside>
          <section className="panel contract-results" aria-live="polite">
            <h2>Validation result</h2>
            {!result ? (
              <div className="contract-no-result">
                <FlaskConical size={30} />
                <h3>No contract check yet</h3>
                <p>
                  Validate your example data to see field-level errors. No
                  execution status or model output will be fabricated.
                </p>
              </div>
            ) : (
              <>
                <div className="contract-check">
                  <span>Input schema</span>
                  <Badge tone={result.input_valid ? "green" : "amber"}>
                    {result.input_valid ? (
                      <Check size={12} />
                    ) : (
                      <CircleAlert size={12} />
                    )}{" "}
                    {result.input_valid ? "Valid" : "Invalid"}
                  </Badge>
                </div>
                <div className="contract-check">
                  <span>Output schema</span>
                  <Badge
                    tone={
                      result.output_valid === null
                        ? "neutral"
                        : result.output_valid
                          ? "green"
                          : "amber"
                    }
                  >
                    {result.output_valid === null
                      ? "Not checked"
                      : result.output_valid
                        ? "Valid"
                        : "Invalid"}
                  </Badge>
                </div>
                {result.errors.map((e, i) => (
                  <div className="contract-field-error" key={`${e.path}-${i}`}>
                    <code>{e.path}</code>
                    <span>{e.message}</span>
                  </div>
                ))}
                <div className="contract-verified">
                  <ShieldCheck size={15} />
                  Checked against frozen hash {result.config_hash.slice(0, 12)}…
                </div>
                <p className="field-hint">
                  Provider calls: 0 · No execution created · No cost incurred by
                  a model
                </p>
              </>
            )}
          </section>
          <details className="panel contract-schema">
            <summary>Frozen input and output schemas</summary>
            <pre>
              {JSON.stringify(
                {
                  input_schema: version.config.input_schema,
                  output_schema: version.config.output_schema,
                },
                null,
                2,
              )}
            </pre>
          </details>
        </aside>
      </div>
    </>
  );
}
