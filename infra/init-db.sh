#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v app_password="$APP_DB_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE ff_app LOGIN PASSWORD %L', :'app_password') \gexec
GRANT CONNECT ON DATABASE flowforge TO ff_app;
GRANT USAGE ON SCHEMA public TO ff_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ff_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ff_app;
CREATE DATABASE flowforge_test;
SQL
